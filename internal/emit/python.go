package emit

import (
	"fmt"
	"sort"
	"strings"

	"github.com/fa33az/logsynth/internal/schema"
)

// Python renders a dependency-free parser module for s. The module exposes
// parse(line), parse_all(path) and a dataclass per record.
func Python(s *schema.Schema) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, `"""Code generated by logsynth from %s. DO NOT EDIT."""`+"\n\n", s.Source)
	b.WriteString("from __future__ import annotations\n\n")

	imports := map[string]bool{"dataclasses": true, "typing": true}
	switch s.Mode {
	case schema.ModePositional, schema.ModeKV:
		imports["re"] = true
	case schema.ModeJSON:
		imports["json"] = true
	default:
		return "", fmt.Errorf("emit/python: unsupported mode %q", s.Mode)
	}
	names := make([]string, 0, len(imports))
	for name := range imports {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		switch name {
		case "dataclasses":
			b.WriteString("from dataclasses import dataclass\n")
		case "json":
			b.WriteString("import json\n")
		case "re":
			b.WriteString("import re\n")
		case "typing":
			if s.Mode == schema.ModeJSON {
				b.WriteString("from typing import Any, Optional\n")
			} else {
				b.WriteString("from typing import Optional\n")
			}
		}
	}
	b.WriteString("\n")

	if s.Mode == schema.ModePositional {
		fmt.Fprintf(&b, "# Pattern inferred from %d matching lines.\n", s.Matched)
		fmt.Fprintf(&b, "PATTERN = re.compile(r'%s')\n\n", s.Pattern)
	}
	if s.Mode == schema.ModeKV {
		b.WriteString(kvPatternPython)
	}

	writePyDataclass(&b, s)
	if err := writePyParse(&b, s); err != nil {
		return "", err
	}
	writePyParseAll(&b)
	b.WriteString(pyHelpers)
	if s.Mode == schema.ModeKV {
		b.WriteString(pyPairHelper)
	}
	if s.Mode == schema.ModeJSON {
		b.WriteString(pyFlattenHelper)
	}
	b.WriteString(pyMain)
	return b.String(), nil
}

const kvPatternPython = `# Key=value records, quoted values may contain spaces.
_PAIR = re.compile(r'([A-Za-z0-9_.\-]+)=("(?:[^"\\]|\\.)*"|\S+)')

`

func writePyDataclass(b *strings.Builder, s *schema.Schema) {
	b.WriteString("\n@dataclass\nclass Line:\n")
	b.WriteString("    \"\"\"One parsed record.\"\"\"\n\n")
	if len(s.Fields) == 0 {
		b.WriteString("    raw: str\n")
		return
	}
	for _, field := range s.Fields {
		fmt.Fprintf(b, "    %s: %s\n", pyName(field.Name), pyType(field))
	}
}

func writePyParse(b *strings.Builder, s *schema.Schema) error {
	switch s.Mode {
	case schema.ModePositional:
		b.WriteString(`
def parse(line: str) -> Optional[Line]:
    """Return a Line, or None when the record does not match the pattern."""
    match = PATTERN.match(line.rstrip("\r\n"))
    if match is None:
        return None
    got = match.groupdict()
    return Line(
`)
		for _, field := range s.Fields {
			fmt.Fprintf(b, "        %s=%s,\n", pyName(field.Name), pyConvert(field, fmt.Sprintf(`got["%s"]`, field.Name)))
		}
		b.WriteString("    )\n\n")
	case schema.ModeKV:
		b.WriteString(`
def parse(line: str) -> Optional[Line]:
    """Return a Line, or None when the record carries no key=value pairs."""
    pairs = _pairs(line)
    if not pairs:
        return None
    return Line(
`)
		for _, field := range s.Fields {
			key := field.Key
			if key == "" {
				key = field.Name
			}
			fmt.Fprintf(b, "        %s=%s,\n", pyName(field.Name), pyConvert(field, fmt.Sprintf(`pairs.get("%s", "")`, key)))
		}
		b.WriteString("    )\n\n")
	case schema.ModeJSON:
		b.WriteString(`
def parse(line: str) -> Optional[Line]:
    """Return a Line, or None when the line is not a JSON object."""
    try:
        raw = json.loads(line)
    except json.JSONDecodeError:
        return None
    if not isinstance(raw, dict):
        return None
    flat: dict[str, Any] = {}
    _flatten("", raw, flat)
    return Line(
`)
		for _, field := range s.Fields {
			key := field.Key
			if key == "" {
				key = field.Name
			}
			fmt.Fprintf(b, "        %s=%s,\n", pyName(field.Name), pyConvert(field, fmt.Sprintf(`flat.get("%s")`, key)))
		}
		b.WriteString("    )\n\n")
	default:
		return fmt.Errorf("emit/python: unsupported mode %q", s.Mode)
	}
	return nil
}

func writePyParseAll(b *strings.Builder) {
	b.WriteString(`def parse_all(path: str) -> list[Line]:
    """Parse every non-empty line of path, skipping records that do not match."""
    out: list[Line] = []
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            if not raw.strip():
                continue
            record = parse(raw)
            if record is not None:
                out.append(record)
    return out


`)
}

func pyType(field schema.Field) string {
	switch field.Type {
	case "int", "float":
		return "Optional[" + field.Type + "]"
	case "bool":
		return "bool"
	}
	return "str"
}

func pyConvert(field schema.Field, expr string) string {
	switch field.Type {
	case "int":
		return "_as_int(" + expr + ")"
	case "float":
		return "_as_float(" + expr + ")"
	case "bool":
		return "_as_bool(" + expr + ")"
	}
	return "_as_str(" + expr + ")"
}

func pyName(name string) string {
	var b strings.Builder
	for i, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r == '_':
			b.WriteRune(r)
		case r >= '0' && r <= '9':
			if i == 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "field"
	}
	return out
}

const pyMain = `
if __name__ == "__main__":
    import sys

    for record in parse_all(sys.argv[1]):
        print(record)
`
