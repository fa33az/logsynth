// Package emit renders a schema into standalone parser code. Emitters are
// pure: same schema in, byte-identical output out.
package emit

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"

	"github.com/fa33az/logsynth/internal/schema"
)

// GoOptions configures the Go emitter.
type GoOptions struct {
	// Package is the generated package name. Empty means "logs".
	Package string
	// Sample holds raw lines embedded in the generated _test.go.
	Sample []string
}

// Go renders a self-contained Go parser for s. The returned test source is
// empty when no sample lines were supplied.
func Go(s *schema.Schema, opts GoOptions) (string, string, error) {
	pkg := opts.Package
	if pkg == "" {
		pkg = "logs"
	}
	names := goFieldNames(s.Fields)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by logsynth from %s. DO NOT EDIT.\n\n", s.Source)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	writeImports(&b, s.Mode)
	writeStruct(&b, s, names)
	if s.Mode == schema.ModePositional {
		fmt.Fprintf(&b, "// Pattern is the regexp inferred from %d matching lines.\n", s.Matched)
		fmt.Fprintf(&b, "var Pattern = regexp.MustCompile(%s)\n\n", rawLiteral(s.Pattern))
	}
	if err := writeParse(&b, s, names); err != nil {
		return "", "", err
	}
	writeParseAll(&b)

	src, err := formatSource(b.String())
	if err != nil {
		return "", "", fmt.Errorf("emit/go: generated source does not parse: %w", err)
	}
	test, err := goTest(s, pkg, opts.Sample)
	if err != nil {
		return "", "", err
	}
	return src, test, nil
}

// formatSource runs gofmt over generated code, which also proves the emitted
// source parses before it ever reaches disk.
func formatSource(src string) (string, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return "", err
	}
	return string(out), nil
}

func writeImports(b *strings.Builder, mode schema.Mode) {
	imports := []string{"bufio", "fmt", "io", "strconv", "strings"}
	switch mode {
	case schema.ModePositional:
		imports = append(imports, "regexp")
	case schema.ModeJSON:
		imports = append(imports, "encoding/json")
	}
	sort.Strings(imports)
	b.WriteString("import (\n")
	for _, imp := range imports {
		fmt.Fprintf(b, "\t%q\n", imp)
	}
	b.WriteString(")\n\n")
}

func writeStruct(b *strings.Builder, s *schema.Schema, names []string) {
	b.WriteString("// Line is one parsed record. Numeric fields that are nullable in the\n")
	b.WriteString("// log are pointers so an absent value stays distinguishable from zero.\n")
	b.WriteString("type Line struct {\n")
	for i, field := range s.Fields {
		tag := field.Name
		if isPointer(field) {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", names[i], goType(field), tag)
	}
	b.WriteString("}\n\n")
}

func writeParseAll(b *strings.Builder) {
	b.WriteString(`// ParseAll parses every non-empty line from r. It stops at the first line
// that does not match and returns the records parsed so far.
func ParseAll(r io.Reader) ([]Line, error) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	out := make([]Line, 0, 256)
	for n := 1; sc.Scan(); n++ {
		raw := sc.Text()
		if strings.TrimSpace(raw) == "" {
			continue
		}
		line, err := Parse(raw)
		if err != nil {
			return out, fmt.Errorf("line %d: %w", n, err)
		}
		out = append(out, line)
	}
	if err := sc.Err(); err != nil {
		return out, err
	}
	return out, nil
}
`)
}

func goType(field schema.Field) string {
	switch field.Type {
	case "int":
		if field.Nullable {
			return "*int64"
		}
		return "int64"
	case "float":
		if field.Nullable {
			return "*float64"
		}
		return "float64"
	case "bool":
		return "bool"
	}
	return "string"
}

func isPointer(field schema.Field) bool {
	return field.Nullable && (field.Type == "int" || field.Type == "float")
}

// goFieldNames converts schema names to exported Go identifiers, keeping them
// unique even after the transformation.
func goFieldNames(fields []schema.Field) []string {
	names := make([]string, len(fields))
	used := make(map[string]int, len(fields))
	for i, field := range fields {
		name := goName(field.Name)
		used[name]++
		if n := used[name]; n > 1 {
			name = fmt.Sprintf("%s%d", name, n)
		}
		names[i] = name
	}
	return names
}

// initialisms maps name fragments to their conventional Go spelling, so
// "http_user_agent" becomes HTTPUserAgent rather than HttpUserAgent.
var initialisms = map[string]string{
	"api": "API", "cpu": "CPU", "db": "DB", "dns": "DNS", "http": "HTTP",
	"https": "HTTPS", "id": "ID", "ip": "IP", "json": "JSON", "sql": "SQL",
	"tcp": "TCP", "tls": "TLS", "ts": "TS", "ua": "UA", "udp": "UDP",
	"uri": "URI", "url": "URL", "uuid": "UUID",
}

func goName(name string) string {
	words := strings.FieldsFunc(name, func(r rune) bool {
		switch r {
		case '_', '-', '.', ' ', ':':
			return true
		}
		return false
	})
	if len(words) == 0 {
		return "Field"
	}
	var b strings.Builder
	for _, word := range words {
		if initialism, ok := initialisms[strings.ToLower(word)]; ok {
			b.WriteString(initialism)
			continue
		}
		runes := []rune(word)
		b.WriteString(strings.ToUpper(string(runes[0])))
		b.WriteString(string(runes[1:]))
	}
	out := b.String()
	if first := rune(out[0]); first >= '0' && first <= '9' {
		out = "F" + out
	}
	return out
}

// rawLiteral renders s as a Go string literal, preferring a raw string so the
// emitted code stays readable.
func rawLiteral(s string) string {
	if strings.ContainsRune(s, '`') {
		return strconv.Quote(s)
	}
	return "`" + s + "`"
}
