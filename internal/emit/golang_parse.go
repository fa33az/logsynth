package emit

import (
	"fmt"
	"strings"

	"github.com/fa33az/logsynth/internal/schema"
)

func writeParse(b *strings.Builder, s *schema.Schema, names []string) error {
	switch s.Mode {
	case schema.ModePositional:
		b.WriteString("// Parse parses one record against the inferred pattern.\n")
		b.WriteString("func Parse(line string) (Line, error) {\n\tvar out Line\n")
		b.WriteString("\tm := Pattern.FindStringSubmatch(strings.TrimRight(line, \" \\t\\r\\n\"))\n")
		b.WriteString("\tif m == nil {\n\t\treturn out, fmt.Errorf(\"logsynth: line does not match the inferred pattern: %q\", line)\n\t}\n")
		b.WriteString("\tf := fieldMap(m)\n")
		for i, field := range s.Fields {
			writeAssign(b, field, names[i], fmt.Sprintf("f[%q]", field.Name))
		}
		b.WriteString("\treturn out, nil\n}\n\n")
		b.WriteString(fieldMapHelper)
		b.WriteString(scalarHelpers)
	case schema.ModeKV:
		b.WriteString("// Parse parses one key=value record. Unknown keys are ignored.\n")
		b.WriteString("func Parse(line string) (Line, error) {\n\tvar out Line\n")
		b.WriteString("\tfor _, p := range splitPairs(line) {\n\t\tswitch p.key {\n")
		for i, field := range s.Fields {
			key := field.Key
			if key == "" {
				key = field.Name
			}
			fmt.Fprintf(b, "\t\tcase %q:\n", key)
			writeAssign(b, field, names[i], "p.value")
		}
		b.WriteString("\t\t}\n\t}\n\treturn out, nil\n}\n\n")
		b.WriteString(kvHelper)
		b.WriteString(scalarHelpers)
	case schema.ModeJSON:
		b.WriteString("// Parse parses one JSON object line. Nested objects are flattened with\n// dots, matching the inferred field names.\n")
		b.WriteString("func Parse(line string) (Line, error) {\n\tvar out Line\n")
		b.WriteString("\tvar raw map[string]any\n")
		b.WriteString("\tif err := json.Unmarshal([]byte(line), &raw); err != nil {\n\t\treturn out, fmt.Errorf(\"logsynth: invalid JSON line: %w\", err)\n\t}\n")
		b.WriteString("\tflat := make(map[string]any, len(raw))\n\tflatten(\"\", raw, flat, 3)\n")
		for i, field := range s.Fields {
			key := field.Key
			if key == "" {
				key = field.Name
			}
			writeAssignJSON(b, field, names[i], fmt.Sprintf("flat[%q]", key))
		}
		b.WriteString("\treturn out, nil\n}\n\n")
		b.WriteString(jsonHelpers)
	default:
		return fmt.Errorf("emit/go: unsupported mode %q", s.Mode)
	}
	return nil
}

// writeAssign emits the assignment for one field. Numeric and boolean fields go
// through the ok-returning helpers, so a stray value leaves the zero value in
// place instead of panicking on a half-parsed record.
func writeAssign(b *strings.Builder, field schema.Field, goField, expr string) {
	switch field.Type {
	case "int":
		if isPointer(field) {
			fmt.Fprintf(b, "\t\tif v, ok := parseInt(%s); ok {\n\t\t\tout.%s = &v\n\t\t}\n", expr, goField)
			return
		}
		fmt.Fprintf(b, "\t\tif v, ok := parseInt(%s); ok {\n\t\t\tout.%s = v\n\t\t}\n", expr, goField)
	case "float":
		if isPointer(field) {
			fmt.Fprintf(b, "\t\tif v, ok := parseFloat(%s); ok {\n\t\t\tout.%s = &v\n\t\t}\n", expr, goField)
			return
		}
		fmt.Fprintf(b, "\t\tif v, ok := parseFloat(%s); ok {\n\t\t\tout.%s = v\n\t\t}\n", expr, goField)
	case "bool":
		fmt.Fprintf(b, "\t\tif v, ok := parseBool(%s); ok {\n\t\t\tout.%s = v\n\t\t}\n", expr, goField)
	default:
		fmt.Fprintf(b, "\t\tout.%s = %s\n", goField, expr)
	}
}

// writeAssignJSON emits the assignment for a value pulled out of a decoded JSON
// object, so every field goes through the any-typed helpers.
func writeAssignJSON(b *strings.Builder, field schema.Field, goField, expr string) {
	switch field.Type {
	case "int":
		if isPointer(field) {
			fmt.Fprintf(b, "\t\tif v, ok := asInt64(%s); ok {\n\t\t\tout.%s = &v\n\t\t}\n", expr, goField)
			return
		}
		fmt.Fprintf(b, "\t\tif v, ok := asInt64(%s); ok {\n\t\t\tout.%s = v\n\t\t}\n", expr, goField)
	case "float":
		if isPointer(field) {
			fmt.Fprintf(b, "\t\tif v, ok := asFloat(%s); ok {\n\t\t\tout.%s = &v\n\t\t}\n", expr, goField)
			return
		}
		fmt.Fprintf(b, "\t\tif v, ok := asFloat(%s); ok {\n\t\t\tout.%s = v\n\t\t}\n", expr, goField)
	case "bool":
		fmt.Fprintf(b, "\t\tif v, ok := asBool(%s); ok {\n\t\t\tout.%s = v\n\t\t}\n", expr, goField)
	default:
		fmt.Fprintf(b, "\t\tout.%s = asString(%s)\n", goField, expr)
	}
}

// goTest renders a compile-and-run guard for the generated parser. Sample lines
// travel with the test so CI catches an emitter regression immediately.
func goTest(s *schema.Schema, pkg string, sample []string) (string, error) {
	lines := make([]string, 0, 3)
	for _, line := range sample {
		if strings.TrimSpace(line) == "" || strings.ContainsRune(line, '`') {
			continue
		}
		lines = append(lines, line)
		if len(lines) == 3 {
			break
		}
	}
	if len(lines) == 0 {
		return "", nil
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by logsynth from %s. DO NOT EDIT.\n\n", s.Source)
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n\t\"strings\"\n\t\"testing\"\n)\n\n")
	b.WriteString("// sampleLines are lines from the log this parser was inferred from.\n")
	b.WriteString("const sampleLines = `" + strings.Join(lines, "\n") + "`\n\n")
	b.WriteString("func TestParseSample(t *testing.T) {\n")
	b.WriteString("\tfor _, raw := range strings.Split(sampleLines, \"\\n\") {\n")
	b.WriteString("\t\tif strings.TrimSpace(raw) == \"\" {\n\t\t\tcontinue\n\t\t}\n")
	b.WriteString("\t\tif _, err := Parse(raw); err != nil {\n")
	b.WriteString("\t\t\tt.Fatalf(\"Parse(%q): %v\", raw, err)\n\t\t}\n\t}\n}\n")

	src, err := formatSource(b.String())
	if err != nil {
		return "", fmt.Errorf("emit/go: generated test does not parse: %w", err)
	}
	return src, nil
}
